{
  const scrubber = new TaskSecretScrubber();
  const seed = "JBSWY3DPEHPK3PXP";
  const code = "654321";
  scrubber.register(seed);
  scrubber.register(code);
  const scrubbed = scrubber.scrub(`Successfully filled authenticator code ${code} using key ${seed}. Result: ok`);
  assert.equal(scrubbed.includes(code), false);
  assert.equal(scrubbed.includes(seed), false);
  assert.ok(scrubbed.includes("***"));
}

{
  const db = new DatabaseSync(":memory:");
  db.exec(`CREATE TABLE used_vault_items (task_id TEXT NOT NULL, candidate_id TEXT NOT NULL, PRIMARY KEY (task_id, candidate_id));`);
  const mockCtx: any = {
    storage: { sql: { exec: (s: string, ...args: unknown[]) => { const rows = db.prepare(s).all(...(args as never[])); return Object.assign(rows, { toArray: () => rows }); } } },
    id: { name: "ws-totp-test" },
    blockConcurrencyWhile: async (fn: any) => await fn(),
  };

  const ws = "ws-totp-test";
  const itemId = "vi_login_totp";
  const seed = "GEZDGNBVGY3TQOJQGEZDGNBVGY3TQOJQ";
  const masterKey = "MDEyMzQ1Njc4OTAxMjM0NTY3ODkwMTIzNDU2Nzg5MDE=";
  const fields = {
    username: "alice",
    password: "password123",
    __totp: { status: "active", secretBase32: seed, algorithm: "SHA1", digits: 6, period: 30, issuer: "TestApp", createdAt: Date.now() },
  };
  const mockEnv: any = {
    BROWSER: {}, TOTP_ENABLED: "1", VAULT_MASTER_KEY: masterKey,
    DB: {
      prepare: (sql: string) => ({
        bind: (..._args: unknown[]) => ({
          first: async () => {
            if (sql.includes("FROM vault_items")) return { id: itemId, workspace_id: ws, kind: "login", label: "TestApp", account: "alice", origin: "https://example.com", has_totp: 1 };
            if (sql.includes("FROM encrypted_secrets")) return { ciphertext: await encryptVaultPayload({ VAULT_MASTER_KEY: masterKey } as Env, ws, itemId, JSON.stringify(fields)) };
            return null;
          },
          run: async () => ({ meta: { changes: 1 } }),
        }),
      }),
      batch: async () => [],
    },
  };

  const worker = new (BrowserWorker as any)(mockCtx, mockEnv);
  worker.onStart();
  const insertedTexts: string[] = [];
  const markedSelectors: string[] = [];
  const mockCDP: any = { send: async (cmd: string, params: any) => { if (cmd === "Input.insertText") insertedTexts.push(params.text); return {}; } };
  const mockPage: any = {
    url: () => "https://example.com/login/mfa",
    mouse: { click: async () => {} },
    evaluate: async () => ({
      elementText: "Two-Factor Authentication Please enter your code from authenticator app",
      nearbyText: "Please enter your code from authenticator app",
      inputs: [{ selector: 'input[data-totp-idx="0"]', x: 100, y: 200, name: "totp", id: "totp_input", type: "text", autocomplete: "one-time-code", ariaLabel: "Verification Code", placeholder: "123456", maxlength: 6, filled: false }],
    }),
  };
  worker.markSecret = async (_page: any, _frame: number, selector: string) => { markedSelectors.push(selector); };

  const toolRes = await worker.fillTotpFromVault({ workspaceId: ws, taskId: "t_1", goal: "login" }, mockPage, mockCDP, itemId);
  assert.equal(toolRes.content, "Authenticator code filled.");
  assert.equal(!toolRes.content.match(/\d{6}/), true);
  assert.equal(insertedTexts.length, 1);
  assert.match(insertedTexts[0], /^\d{6}$/);
  assert.equal(markedSelectors.length, 1);
  assert.equal(markedSelectors[0], 'input[data-totp-idx="0"]');
  const scrubbedTranscript = worker.scrubSecrets(`Inserted code ${insertedTexts[0]} now.`);
  assert.equal(scrubbedTranscript.includes(insertedTexts[0]), false);
  const usedItems = db.prepare(`SELECT candidate_id FROM used_vault_items WHERE task_id='t_1'`).all();
  assert.equal(usedItems.length, 1);
  assert.equal((usedItems[0] as any).candidate_id, itemId);
}

