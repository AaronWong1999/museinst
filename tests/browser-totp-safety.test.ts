// tests/browser-totp-safety.test.ts — BrowserWorker TOTP safety, detector, and scrubber tests.

import assert from "node:assert/strict";
import { DatabaseSync } from "node:sqlite";
import { detectTotpPrompt } from "../src/vault/totp-detector";
import { BrowserWorker } from "../src/agent/browser-worker";
import { TaskSecretScrubber } from "../src/agent/secret-scrub";
import { encryptVaultPayload } from "../src/vault/service";
import type { Env } from "../src/env";

console.log("▶ Testing browser TOTP safety, detection boundaries & scrubber...");

{
  const res1 = detectTotpPrompt({
    elementText: "Two-Factor Authentication",
    nearbyText: "Please enter the code from your authenticator app",
    attributes: { name: "totp_code", autocomplete: "one-time-code", maxlength: 6 },
  });
  assert.equal(res1.isTotp, true);
  assert.ok(res1.matchedSignals?.includes("autocomplete_one_time_code"));

  const res2 = detectTotpPrompt({
    elementText: "Two-Step Verification",
    nearbyText: "Enter the 6-digit verification code generated by Google Authenticator",
    attributes: { id: "auth-code", maxlength: 6 },
  });
  assert.equal(res2.isTotp, true);
}

{
  const smsRes = detectTotpPrompt({
    elementText: "Two-Factor Authentication",
    nearbyText: "We sent a text message with a 6-digit verification code to your phone (SMS)",
    attributes: { autocomplete: "one-time-code", maxlength: 6 },
  });
  assert.equal(smsRes.isTotp, false);
  assert.equal(smsRes.rejectedReason, "not_totp_prompt");

  const emailRes = detectTotpPrompt({
    elementText: "Verify Your Identity",
    nearbyText: "Enter the email code sent to your email address",
    attributes: { name: "verification_code", maxlength: 6 },
  });
  assert.equal(emailRes.isTotp, false);
  assert.equal(emailRes.rejectedReason, "not_totp_prompt");

  const pushRes = detectTotpPrompt({
    elementText: "Two-Step Verification",
    nearbyText: "Approve on phone using push notification",
    attributes: { id: "code" },
  });
  assert.equal(pushRes.isTotp, false);

  const passkeyRes = detectTotpPrompt({
    elementText: "Sign in with Passkey",
    nearbyText: "Use your security key or biometric passkey",
    attributes: { name: "otp" },
  });
  assert.equal(passkeyRes.isTotp, false);

  const captchaRes = detectTotpPrompt({
    elementText: "Security Check",
    nearbyText: "Please solve the captcha verification",
    attributes: { name: "captcha_code" },
  });
  assert.equal(captchaRes.isTotp, false);

  // The HTML shape used by SMS/email OTP is not sufficient without authenticator-specific evidence.
  const genericOtp = detectTotpPrompt({
    elementText: "Verify your identity",
    nearbyText: "Enter the 6 digit code",
    attributes: { name: "verification_code", autocomplete: "one-time-code", maxlength: 6 },
  });
  assert.equal(genericOtp.isTotp, false);
  assert.equal(genericOtp.rejectedReason, "generic_otp_not_proven_totp");
}

